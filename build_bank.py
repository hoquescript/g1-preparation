#!/usr/bin/env python3
"""Merge questions.csv with options.py into question_bank.js for quiz.html."""
import csv
import json
import sys

from options import OPTIONS


def main():
    with open("questions.csv", encoding="utf-8") as f:
        rows = list(csv.DictReader(f))

    bank, errors = [], []
    for row in rows:
        n = int(row["number"])
        if n not in OPTIONS:
            errors.append(f"{n}: no options")
            continue
        correct, wrong = OPTIONS[n]
        correct = correct or row["answer"]
        choices = [correct, *wrong]
        if len(wrong) != 3 or len({c.lower() for c in choices}) != 4:
            errors.append(f"{n}: need 3 distinct wrong options different from the answer")
        bank.append({"n": n, "q": row["question"], "a": correct, "w": wrong, "e": row["answer"]})

    if errors:
        sys.exit("\n".join(errors))
    with open("question_bank.js", "w", encoding="utf-8") as f:
        f.write("// Generated by build_bank.py - edit options.py instead.\n")
        f.write(f"const QUESTIONS = {json.dumps(bank, ensure_ascii=False, indent=1)};\n")
    print(f"Wrote {len(bank)} questions to question_bank.js")


if __name__ == "__main__":
    main()
