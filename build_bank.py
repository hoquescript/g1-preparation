#!/usr/bin/env python3
"""Merge each category's questions CSV, options and paraphrases, plus duplicates.py, into question_bank.js."""
import csv
import json
import sys

import options
import options_fines
import paraphrases
import paraphrases_fines
from duplicates import DUPLICATES

# id, label, questions CSV, options, paraphrases, offset added to the CSV number to make the global
# question number (kept unique across categories for answer history and duplicate groups).
CATEGORIES = [
    ("rules", "Road Rules", "questions.csv", options.OPTIONS, paraphrases.PARAPHRASES, 0),
    ("fines", "Fines, Limits & Points", "questions_fines.csv", options_fines.OPTIONS, paraphrases_fines.PARAPHRASES, 1000),
]


def distinct_choices(correct, wrong):
    return len(wrong) == 3 and len({c.lower() for c in [correct, *wrong]}) == 4


def main():
    group = {}
    for members in DUPLICATES:
        for n in members:
            if n in group:
                sys.exit(f"{n}: in more than one duplicate group")
            group[n] = members[0]

    bank, errors, unparaphrased = [], [], []
    for cat, label, path, opts, phrases, offset in CATEGORIES:
        with open(path, encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
        for row in rows:
            k = int(row["number"])
            n = offset + k
            if k not in opts:
                errors.append(f"{cat} {k}: no options")
                continue
            correct, wrong = opts[k]
            correct = correct or row["answer"]
            if not distinct_choices(correct, wrong):
                errors.append(f"{cat} {k}: need 3 distinct wrong options different from the answer")
            variants = phrases.get(k, [])
            if not variants:
                unparaphrased.append(f"{cat} {k}")
            for v in variants:
                if isinstance(v, dict) and (set(v) != {"q", "a", "w", "e"} or not distinct_choices(v["a"], v["w"])):
                    errors.append(f"{cat} {k}: positive version needs q, a, e and 3 distinct wrong options")
            entry = {"n": n, "c": cat, "k": k, "q": row["question"], "v": variants,
                     "a": correct, "w": wrong, "e": row["answer"]}
            if n in group:
                entry["g"] = group[n]
            bank.append(entry)

    numbers = {q["n"] for q in bank}
    errors += [f"duplicate group lists {n}, which isn't a question" for n in group if n not in numbers]
    if errors:
        sys.exit("\n".join(errors))
    categories = [{"id": cat, "label": label} for cat, label, *_ in CATEGORIES]
    with open("question_bank.js", "w", encoding="utf-8") as f:
        f.write("// Generated by build_bank.py - edit the options and paraphrases files instead.\n")
        f.write(f"const CATEGORIES = {json.dumps(categories, ensure_ascii=False)};\n")
        f.write(f"const QUESTIONS = {json.dumps(bank, ensure_ascii=False, indent=1)};\n")
    counts = ", ".join(f"{sum(q['c'] == c['id'] for q in bank)} {c['label']}" for c in categories)
    print(f"Wrote {len(bank)} questions to question_bank.js ({counts})")
    if unparaphrased:
        print(f"No paraphrases yet (original wording only): {', '.join(unparaphrased)}")


if __name__ == "__main__":
    main()
